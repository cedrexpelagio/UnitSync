#!/usr/bin/env python3
"""Build the shared bundles. Run from the project root:  python3 build.py
   css/core.css  = tokens + reset + motion + layout + components   (replaces style.css + app-shell.css)
   js/core.js    = core/dom.js + components/ui.js + components/app-shell.js
Page files (css/pages/**, js/pages/**) are loaded individually, as before."""
import os, re
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'assets')
CSS = ['base/tokens', 'base/reset', 'base/motion', 'layout/app-shell', 'layout/auth-card', 'layout/page-header',
       'components/button', 'components/form', 'components/banner', 'components/card', 'components/table',
       'components/tabs', 'components/badge', 'components/modal', 'components/toast']
JS = ['core/dom', 'components/ui', 'components/app-shell']

def cat(kind, names):
    out = []
    for n in names:
        p = os.path.join(ROOT, kind, n + '.' + kind)
        out.append(f'/* ---- {n}.{kind} ---- */\n' + open(p).read().strip() + '\n')
    return '\n'.join(out)

css = '/* UnitSync core bundle - generated by build.py, do not edit. Edit the sources under css/base, layout, components. */\n\n' + cat('css', CSS)
open(os.path.join(ROOT, 'css/core.css'), 'w').write(css)
js = '/* UnitSync core bundle - generated by build.py, do not edit. */\n' + cat('js', JS).replace('/* ----', '//', 0)
open(os.path.join(ROOT, 'js/core.js'), 'w').write(js)

main = '/* Development entry point (uses @import). Production pages load core.css, which build.py generates. */\n' + \
       '\n'.join(f"@import url('{n}.css');" for n in CSS) + '\n'
open(os.path.join(ROOT, 'css/main.css'), 'w').write(main)
print('core.css', len(css) // 1024, 'KB |', 'core.js', len(js) // 1024, 'KB')


# ---------------------------------------------------------------------------
# Compatibility layer: regenerates the ORIGINAL file names at the old paths so
# existing templates keep working with zero edits. Safe to delete once your
# templates point at css/core.css, js/core.js and the css|js/pages/** files.
# ---------------------------------------------------------------------------
def read(kind, name):
    return open(os.path.join(ROOT, kind, name)).read().strip() + '\n'

BANNER = '/* COMPAT: generated by build.py for the original file name. Edit the real source files instead. */\n'
JSBANNER = BANNER.replace('/*', '//').replace(' */', '')

# CSS: old name -> list of new sources
css_compat = {
    'style.css':      ['core.css', 'pages/leader/attendance-sheet.css', 'pages/s1/attendance-matrix.css'],  # included the attendance blocks
    'app-shell.css':  [],                                    # already inside core.css (style.css)
    'auth.css':       ['pages/auth/auth.css'],
    'register.css':   ['pages/auth/register.css'],
    'dashboard.css':  ['pages/s1/dashboard.css'],
    'roster.css':     ['pages/s1/roster.css'],
    's1_manage.css':  ['pages/s1/manage.css'],
    'leader.css':     ['pages/leader/leader.css'],
    'add_cadet.css':  ['pages/leader/add-cadet.css'],
    'admin.css':      ['pages/admin/admin.css'],
}
for old, parts in css_compat.items():
    open(os.path.join(ROOT, 'css', old), 'w').write(BANNER + ''.join(read('css', p) + '\n' for p in parts))

# JS: scripts that use the shared helpers get dom.js prepended so they work standalone
dom = read('js', 'core/dom.js')
js_compat = {
    'ui.js':               [dom, read('js', 'components/ui.js')],
    'app-shell.js':        [read('js', 'components/app-shell.js')],
    'auth.js':             [dom, read('js', 'pages/auth/auth.js')],
    'register.js':         [read('js', 'pages/auth/register.js')],
    'dashboard.js':        [dom, read('js', 'pages/s1/dashboard.js')],
    'roster.js':           [read('js', 'pages/s1/roster.js')],
    's1_manage.js':        [dom, read('js', 'pages/s1/manage.js')],
    'view_attendance.js':  [read('js', 'pages/s1/view-attendance.js')],
    'reassign_officer.js': [read('js', 'pages/s1/reassign-officer.js')],
    'leader.js':           [dom, read('js', 'pages/leader/leader.js')],
    'admin.js':            [dom, read('js', 'pages/admin/admin.js')],
}
for old, parts in js_compat.items():
    open(os.path.join(ROOT, 'js', old), 'w').write(JSBANNER + ';\n'.join(parts))
print('compat files:', len(css_compat), 'css +', len(js_compat), 'js at the original paths')
